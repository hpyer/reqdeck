#!/usr/bin/env node
/**
 * Versioned release flow.
 *
 * 1. bumps manifest.json + package.json;
 * 2. generates the CHANGELOG entry from commits since the previous v* tag;
 * 3. commits the release files, creates v<version>, and pushes branch + tag.
 *
 * GitHub Actions (on the tag) builds the extension and creates the GitHub
 * Release. CHANGELOG.md is written only by this script.
 *
 * Usage: npm run release -- patch|minor|major|<exact-version> [--no-push]
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHANGELOG_HEADER =
  '# Changelog\n\nAll notable changes to ReqDeck are documented here. This file is generated by `npm run release` and should only be modified during a release.';
const args = process.argv.slice(2);
const noPush = args.includes('--no-push');
const spec = args.find((arg) => !arg.startsWith('--'));

function fail(message) {
  console.error(`\n${message}\n`);
  process.exit(1);
}

function git(gitArgs, { allowFail = false, inherit = false } = {}) {
  const result = spawnSync('git', gitArgs, {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: inherit ? 'inherit' : ['ignore', 'pipe', 'pipe'],
  });
  if (result.status !== 0 && !allowFail) {
    const detail = [result.stderr, result.stdout].filter(Boolean).join('\n').trim();
    fail(`git ${gitArgs.join(' ')} failed.${detail ? `\n${detail}` : ''}`);
  }
  return { ok: result.status === 0, out: (result.stdout || '').trim() };
}

function npm(script, npmArgs = []) {
  execFileSync('npm', ['run', script, ...(npmArgs.length ? ['--', ...npmArgs] : [])], {
    cwd: ROOT,
    stdio: 'inherit',
  });
}

function parseVersion(value) {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(value).trim());
  if (!match) return null;
  return { major: Number(match[1]), minor: Number(match[2]), patch: Number(match[3]) };
}

function versionString(v) {
  return `${v.major}.${v.minor}.${v.patch}`;
}

function nextVersion(current, requested) {
  const base = parseVersion(current);
  if (!base) fail(`manifest.json has an invalid version: ${current}`);
  if (requested === 'patch') return versionString({ ...base, patch: base.patch + 1 });
  if (requested === 'minor') return versionString({ ...base, minor: base.minor + 1, patch: 0 });
  if (requested === 'major') return versionString({ ...base, major: base.major + 1, minor: 0, patch: 0 });
  const exact = parseVersion(requested);
  if (!exact) fail('Version must be patch, minor, major, or an exact x.y.z version.');
  return versionString(exact);
}

function compareVersions(a, b) {
  const av = parseVersion(a);
  const bv = parseVersion(b);
  if (!av || !bv) return 0;
  return av.major - bv.major || av.minor - bv.minor || av.patch - bv.patch;
}

function readJson(file) {
  return JSON.parse(readFileSync(resolve(ROOT, file), 'utf8'));
}

function writeJson(file, value) {
  writeFileSync(resolve(ROOT, file), `${JSON.stringify(value, null, 2)}\n`);
}

if (!spec) {
  fail('Usage: npm run release -- patch|minor|major|<exact-version> [--no-push]');
}

const dirty = git(['status', '--porcelain']).out;
if (dirty) {
  fail(
    `Working tree is not clean. Commit or stash these files before releasing:\n${dirty
      .split('\n')
      .map((line) => `  ${line}`)
      .join('\n')}`,
  );
}

const name = git(['config', 'user.name'], { allowFail: true }).out;
const email = git(['config', 'user.email'], { allowFail: true }).out;
if (!name || !email) {
  fail('Set git user.name and user.email before releasing.');
}

const remote = git(['remote', 'get-url', 'origin'], { allowFail: true });
if (!remote.ok || !remote.out) {
  fail('No origin remote. Add your repository remote first, e.g. git remote add origin <your-repo-url>');
}

const manifest = readJson('manifest.json');
const pkg = readJson('package.json');
if (manifest.version !== pkg.version) {
  fail('manifest.json and package.json versions differ. Align them before releasing.');
}

const next = nextVersion(manifest.version, spec);
const previousTag = git(['describe', '--tags', '--abbrev=0', '--match', 'v[0-9]*'], { allowFail: true }).out;
const isFirstRelease = !previousTag;

if (next === manifest.version && !isFirstRelease) {
  fail(`Version ${next} is already released. Choose a higher version.`);
}
if (next !== manifest.version && compareVersions(next, manifest.version) <= 0) {
  fail(`New version ${next} must be greater than the current version ${manifest.version}.`);
}

const tagName = `v${next}`;
if (git(['rev-parse', '-q', '--verify', `refs/tags/${tagName}`], { allowFail: true }).ok) {
  fail(`Tag ${tagName} already exists.`);
}

const changelogPath = resolve(ROOT, 'CHANGELOG.md');
const changelog = readFileSync(changelogPath, 'utf8');
if (changelog.includes(`## [${next}]`)) {
  fail(`CHANGELOG.md already has a ${next} section.`);
}

const range = previousTag ? `${previousTag}..HEAD` : 'HEAD';
const log = git(['log', range, '--no-merges', '--pretty=format:%h%x09%s'], { allowFail: true }).out;
const commits = log
  ? log
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean)
      .map((line) => {
        const tab = line.indexOf('\t');
        return tab === -1
          ? { hash: line, subject: '(no subject)' }
          : { hash: line.slice(0, tab), subject: line.slice(tab + 1) };
      })
  : [];

if (!commits.length && !isFirstRelease) {
  fail(`No commits since ${previousTag}. Nothing to release.`);
}

console.log(`\nReleasing ${next}${previousTag ? ` (changes since ${previousTag})` : ' (first release)'}\n`);
console.log('Running tests and syntax checks...');
npm('test');
npm('check');

const date = new Date().toISOString().slice(0, 10);
const items = commits.length
  ? commits.map((commit) => `- ${commit.subject} (${commit.hash})`).join('\n')
  : '- Initial release.';
const entry = `## [${next}] - ${date}\n\n### Changes\n\n${items}`;
const firstEntry = changelog.indexOf('\n## [');
const previousEntries = firstEntry === -1 ? '' : changelog.slice(firstEntry + 1).trim();
const nextChangelog = `${CHANGELOG_HEADER}\n\n${entry}${previousEntries ? `\n\n${previousEntries}` : ''}\n`;
writeFileSync(changelogPath, nextChangelog);
writeJson('manifest.json', { ...manifest, version: next });
writeJson('package.json', { ...pkg, version: next });

git(['add', 'CHANGELOG.md', 'manifest.json', 'package.json']);
git(['commit', '-m', `chore(release): v${next}`], { inherit: true });
git(['tag', '-a', tagName, '-m', `ReqDeck v${next}`]);

if (noPush) {
  console.log(`\nCreated local commit and ${tagName}. Push when ready:`);
  console.log(`  git push origin HEAD\n  git push origin ${tagName}`);
  process.exit(0);
}

console.log('\nPushing branch and tag...');
git(['push', 'origin', 'HEAD'], { inherit: true });
git(['push', 'origin', tagName], { inherit: true });

console.log(`\nPushed ${tagName}. GitHub Actions will build the package and publish the GitHub Release.`);
console.log('CHANGELOG.md was updated only as part of this release.');

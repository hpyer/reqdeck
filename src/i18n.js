const FIELD_PREFIX = {
  pattern: 'Pattern',
  redirect: 'Redirect',
  cookie: 'Cookie',
  headers: 'Headers',
  header: 'Header',
};

export function errorMessage(code, field) {
  if (!code) return '';
  const prefix = FIELD_PREFIX[field] || 'Pattern';
  const suffix = CODE_SUFFIX[code] || 'Invalid';
  return t(`error${prefix}${suffix}`);
}
